async def register_generated_file(
    file_path: str, 
    filename: str, 
    purpose: str = "assistant_generated",
    owner_id: Optional[str] = None,
    mcp_session_id: Optional[str] = None
) -> Optional[str]:
    """
    Register a generated file with the orchestration service's file management system.
    
    Args:
        file_path: Absolute path to the generated file
        filename: Original filename for display purposes
        purpose: File purpose (default: "assistant_generated")
        owner_id: User ID who owns this file
        mcp_session_id: Session ID for context
        
    Returns:
        File ID if registration successful, None if failed
    """
    orchestration_url = os.getenv("ORCHESTRATION_SERVICE_URL", "http://orchestration_service:8084")
    
    if not os.path.exists(file_path):
        logger.warning(f"Cannot register non-existent file: {file_path}")
        return None
    
    try:
        file_size = os.path.getsize(file_path)
        file_id = f"file-{uuid.uuid4()}"
        
        # Create file metadata
        file_metadata = {
            "id": file_id,
            "object": "file",
            "bytes": file_size,
            "created_at": int(time.time()),
            "filename": filename,
            "purpose": purpose,
            "status": "processed",
            "owner_id": owner_id,
            "mcp_session_id": mcp_session_id,
            "generated_by": "sandbox_mcp_server"
        }
        
        # Register with orchestration service via internal API
        async with httpx.AsyncClient(timeout=10.0) as client:
            response = await client.post(
                f"{orchestration_url}/v1/files/internal/register",
                json={
                    "file_metadata": file_metadata,
                    "file_path": file_path
                },
                headers={
                    "Content-Type": "application/json",
                    "X-Service-Name": "sandbox_mcp_server",
                    "X-Session-ID": mcp_session_id or "unknown"
                }
            )
            
            if response.status_code == 201:
                logger.info(f"Successfully registered generated file {filename} with ID {file_id}")
                return file_id
            else:
                logger.warning(f"Failed to register file {filename}: {response.status_code} - {response.text}")
                return None
                
    except Exception as e:
        logger.error(f"Error registering generated file {filename}: {e}", exc_info=True)
        return None

async def scan_and_register_generated_files(
    directory: str, 
    owner_id: Optional[str] = None,
    mcp_session_id: Optional[str] = None,
    before_files: Optional[set] = None
) -> list:
    """
    Scan directory for newly generated files and register them.
    
    Args:
        directory: Directory to scan for generated files
        owner_id: User ID who owns these files
        mcp_session_id: Session ID for context
        before_files: Set of files that existed before (to detect new files)
        
    Returns:
        List of registered file metadata
    """
    registered_files = []  # TODO: Expose this as an optional parameter with default list of extensions
    
    try:
        # Get current files
        current_files = set(glob.glob(os.path.join(directory, "*")))
        
        # If we have before_files, only process new files
        if before_files is not None:
            new_files = current_files - before_files
        else:
            # Process all generated files in directory (plots, text files, etc.)
            # TODO: Make this configurable
            generated_extensions = {'.png', '.jpg', '.jpeg', '.svg', '.pdf', '.gif', 
                                    '.py', '.js', '.sh', '.R', '.julia', '.scala',
                                    '.java', '.go', '.rs', '.cpp', '.c', '.ipynb',
                                    '.h', '.hpp', '.cxx', '.Rcmd', '.Rscript',
                                    '.doc', '.docx', '.ppt', '.pptx', '.xls', '.xlsx',
                                    '.log', '.rtf', '.xml',
                                    '.txt', '.csv', '.json', '.html', '.md'}
            new_files = {f for f in current_files 
                        if Path(f).suffix.lower() in generated_extensions 
                        and os.path.isfile(f)}
        
        for file_path in new_files:
            if os.path.isfile(file_path):
                filename = os.path.basename(file_path)
                file_id = await register_generated_file(
                    file_path=file_path,
                    filename=filename,
                    purpose="assistant_generated",
                    owner_id=owner_id,
                    mcp_session_id=mcp_session_id
                )
                
                if file_id:
                    registered_files.append({
                        "file_id": file_id,
                        "filename": filename,
                        "file_path": file_path,
                        "size": os.path.getsize(file_path)
                    })
        
        if registered_files:
            logger.info(f"Successfully registered {len(registered_files)} generated files")
        
        return registered_files
        
    except Exception as e:
        logger.error(f"Error scanning and registering generated files: {e}", exc_info=True)
        return []

async def _copy_files_from_nested_container(session, logger):
    """
    Copy files from nested container's /app/data/uploaded_files to sandbox_mcp_server's shared volume.
    This is a workaround for Docker-in-Docker volume mount issues.
    """
    try:
        logger.info("COPY-BACK DEBUG: Starting copy-back mechanism")
        
        # Get the nested container reference
        nested_container = session._session.container
        shared_volume_path = "/app/data/uploaded_files"
        
        logger.info(f"COPY-BACK DEBUG: Container reference: {nested_container}")
        logger.info(f"COPY-BACK DEBUG: Target shared volume path: {shared_volume_path}")
        
        # Ensure target directory exists
        os.makedirs(shared_volume_path, exist_ok=True)
        logger.info(f"COPY-BACK DEBUG: Ensured target directory exists: {shared_volume_path}")
        
        logger.info(f"COPY-BACK DEBUG: Attempting to copy files from nested container to shared volume")
        
        # Get list of files in nested container's upload directory
        try:
            logger.info("COPY-BACK DEBUG: Executing find command in nested container")
            result = nested_container.exec_run(f"find /app/data/uploaded_files -type f", demux=True)
            logger.info(f"COPY-BACK DEBUG: Find command exit code: {result.exit_code}")
            
            if result.exit_code == 0:
                stdout, stderr = result.output
                logger.info(f"COPY-BACK DEBUG: Find command stdout: {stdout}")
                logger.info(f"COPY-BACK DEBUG: Find command stderr: {stderr}")
                
                if stdout:
                    files_to_copy = stdout.decode('utf-8').strip().split('\n')
                    files_to_copy = [f for f in files_to_copy if f.strip()]  # Remove empty lines
                    
                    logger.info(f"COPY-BACK DEBUG: Found {len(files_to_copy)} files to copy: {files_to_copy}")
                    
                    # Copy each file from nested container to shared volume
                    for file_path in files_to_copy:
                        if file_path.strip():
                            try:
                                logger.info(f"COPY-BACK DEBUG: Processing file: {file_path}")
                                
                                # Get file from nested container
                                data, stat = nested_container.get_archive(file_path)
                                logger.info(f"COPY-BACK DEBUG: Retrieved archive for {file_path}")
                                
                                # Extract filename from path
                                filename = os.path.basename(file_path)
                                local_path = os.path.join(shared_volume_path, filename)
                                logger.info(f"COPY-BACK DEBUG: Target local path: {local_path}")
                                
                                # Extract and save the file
                                import tarfile
                                import io
                                
                                tar_stream = io.BytesIO(b"".join(data))
                                with tarfile.open(fileobj=tar_stream, mode='r') as tar:
                                    for member in tar:
                                        if member.isfile():
                                            file_content = tar.extractfile(member).read()
                                            with open(local_path, 'wb') as f:
                                                f.write(file_content)
                                            logger.info(f"COPY-BACK DEBUG: Successfully copied {filename} to shared volume: {local_path}")
                                            logger.info(f"COPY-BACK DEBUG: File size: {len(file_content)} bytes")
                                            
                            except Exception as copy_error:
                                logger.warning(f"Failed to copy file {file_path}: {copy_error}")
                else:
                    logger.info("COPY-BACK DEBUG: No files found in nested container's upload directory - stdout was empty")
            else:
                logger.warning(f"COPY-BACK DEBUG: Failed to list files in nested container: exit_code={result.exit_code}, stderr={stderr}")
                
        except Exception as list_error:
            logger.error(f"COPY-BACK DEBUG: Error listing files in nested container: {list_error}", exc_info=True)
            
    except Exception as e:
        logger.error(f"COPY-BACK DEBUG: Error copying files from nested container: {e}", exc_info=True)

def _generate_plot_metadata(plot_filepath: str, mcp_session_id: Optional[str] = None) -> Dict[str, Any]:
    """
    Generate comprehensive metadata for a plot file.

    Args:
        plot_filepath: Absolute path to the plot file
        mcp_session_id: Optional MCP session ID for context

    Returns:
        Dictionary with comprehensive plot metadata
    """
    # Format mapping (expanded per user request)
    format_map = {
        # Raster formats
        ".png": "png",
        ".jpg": "jpeg",
        ".jpeg": "jpeg",
        ".bmp": "bmp",
        ".tiff": "tiff",
        ".tif": "tiff",
        ".gif": "gif",
        ".webp": "webp",
        ".ico": "ico",
        # Vector formats
        ".svg": "svg",
        ".eps": "eps",
        # Document formats
        ".pdf": "pdf",
        # Interactive formats
        ".html": "html"
    }

    # MIME type mapping
    mime_map = {
        "png": "image/png",
        "jpeg": "image/jpeg",
        "bmp": "image/bmp",
        "tiff": "image/tiff",
        "gif": "image/gif",
        "webp": "image/webp",
        "ico": "image/x-icon",
        "svg": "image/svg+xml",
        "eps": "application/postscript",
        "pdf": "application/pdf",
        "html": "text/html"
    }

    # Raster formats that support PIL dimension extraction
    raster_formats = {"png", "jpeg", "bmp", "tiff", "gif", "webp", "ico"}

    try:
        # Extract filename and format
        filename = os.path.basename(plot_filepath)
        file_extension = Path(plot_filepath).suffix.lower()
        format_str = format_map.get(file_extension, "unknown")

        # Get file size
        size_bytes = os.path.getsize(plot_filepath)

        # Generate URLs — strip /v1 suffix if present to avoid double /v1/v1/ prefix
        # (PUBLIC_GATEWAY_URL may include /v1 from AGENT_GATEWAY_EXTERNAL_URL in docker-compose)
        agent_gateway_url = os.getenv("PUBLIC_GATEWAY_URL", "http://localhost:8083").rstrip("/")
        if agent_gateway_url.endswith("/v1"):
            agent_gateway_url = agent_gateway_url[:-3]
        plot_url = f"{agent_gateway_url}/v1/plots/{filename}"

        # Calculate relative path
        relative_path = f"data/uploaded_files/plots/{filename}"

        # Base metadata (always present)
        metadata = {
            "plot_url": plot_url,
            "filename": filename,
            "file_path": plot_filepath,
            "relative_path": relative_path,
            "format": format_str,
            "size_bytes": size_bytes,
            "mime_type": mime_map.get(format_str, "application/octet-stream"),
            "created_at": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
            "session_id": mcp_session_id or "unknown"
        }

        # Add dimensions for raster formats only
        if format_str in raster_formats:
            try:
                from PIL import Image
                with Image.open(plot_filepath) as img:
                    metadata["width_pixels"] = img.width
                    metadata["height_pixels"] = img.height
                    logger.info(f"Extracted dimensions for {filename}: {img.width}x{img.height}")
            except Exception as dim_error:
                logger.warning(f"Could not extract dimensions for {filename}: {dim_error}")
                # Dimensions are optional, continue without them

        logger.info(f"Generated metadata for plot: {filename} ({format_str}, {size_bytes} bytes)")
        return metadata

    except Exception as e:
        logger.error(f"Error generating plot metadata for {plot_filepath}: {e}", exc_info=True)
        # Return minimal metadata on error
        return {
            "filename": os.path.basename(plot_filepath),
            "file_path": plot_filepath,
            "error": str(e)
        }

def get_optimal_sandbox_image(language: str, generate_plot: bool, provided_image: Optional[str] = None) -> Optional[str]:
    """
    Determine the optimal Docker image for sandbox execution based on requirements.

    Args:
        language: Programming language (python, javascript, shell)
        generate_plot: Whether plotting capabilities are needed
        provided_image: User-provided custom image (takes precedence)

    Returns:
        Docker image name or None to use llm-sandbox defaults
    """
    if provided_image:
        logger.info(f"Using user-provided sandbox image: {provided_image}")
        return provided_image

    if language.lower() == "python" and generate_plot:
        # Use jupyter/scipy-notebook which has matplotlib, numpy, pandas, seaborn pre-installed
        # Alternative options:
        # - jupyter/datascience-notebook (has more ML libraries)
        # - continuumio/anaconda3 (full Anaconda distribution)
        # - python:3.11 with pip install (but slower)
        scientific_image = "jupyter/scipy-notebook:latest"
        logger.info(f"Using scientific Python image for plotting: {scientific_image}")
        return scientific_image

    # For non-plotting cases, let llm-sandbox choose the default image
    logger.info(f"Using llm-sandbox default image for {language}")
    return None

