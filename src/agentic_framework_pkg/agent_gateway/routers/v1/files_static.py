"""
Secure file serving endpoints for the Agent Gateway.

Provides authenticated access to files in the shared uploads directory,
including plots generated by the sandbox and other user files.
"""
import os
from fastapi import APIRouter, HTTPException, Depends, Request
from fastapi.responses import FileResponse
from typing import Optional

from ...auth import AuthCredentials, get_current_user
from ....logger_config import get_logger

router = APIRouter()
logger = get_logger(__name__)

# Base directory for shared uploads
SHARED_UPLOADS_DIR = "/app/data/uploaded_files"

async def validate_file_access(
    file_path: str, 
    user: AuthCredentials,
    request: Request
) -> str:
    """
    Validate that the user has permission to access the requested file.
    
    Args:
        file_path: Requested file path (relative to uploads dir)
        user: Authenticated user credentials
        request: FastAPI request object
        
    Returns:
        Absolute path to file if access is granted
        
    Raises:
        HTTPException: If access is denied or file doesn't exist
    """
    # Normalize the file path to prevent directory traversal
    clean_path = os.path.normpath(file_path.lstrip('/'))
    
    # Prevent directory traversal attacks
    if '..' in clean_path or clean_path.startswith('/'):
        logger.warning(f"Directory traversal attempt by user {user.username}: {file_path}")
        raise HTTPException(status_code=403, detail="Invalid file path")
    
    # Construct absolute path
    abs_path = os.path.join(SHARED_UPLOADS_DIR, clean_path)
    
    # Ensure the resolved path is still within the uploads directory
    if not abs_path.startswith(os.path.abspath(SHARED_UPLOADS_DIR)):
        logger.warning(f"Path escape attempt by user {user.username}: {abs_path}")
        raise HTTPException(status_code=403, detail="Invalid file path")
    
    # Check if file exists
    if not os.path.exists(abs_path):
        logger.info(f"File not found: {abs_path} (requested by {user.username})")
        raise HTTPException(status_code=404, detail="File not found")
    
    # Additional authorization checks can be added here based on:
    # - User groups/roles
    # - File ownership (if metadata is tracked)
    # - File type restrictions
    # - Time-based access controls
    
    # For now, allow access to all authenticated users
    # This can be enhanced with more granular permissions
    logger.info(f"File access granted to {user.username}: {clean_path}")
    return abs_path

@router.get("/files/{file_path:path}")
async def serve_user_file(
    file_path: str,
    user: AuthCredentials = Depends(get_current_user),
    request: Request = None
):
    """
    Serve files from the shared uploads directory with authentication.
    
    This endpoint provides secure access to user uploads, plots, and other
    files while maintaining the authentication and authorization flow.
    """
    try:
        abs_path = await validate_file_access(file_path, user, request)
        
        # Determine content type based on file extension
        file_ext = os.path.splitext(abs_path)[1].lower()
        
        media_types = {
            '.png': 'image/png',
            '.jpg': 'image/jpeg', 
            '.jpeg': 'image/jpeg',
            '.gif': 'image/gif',
            '.svg': 'image/svg+xml',
            '.pdf': 'application/pdf',
            '.csv': 'text/csv',
            '.txt': 'text/plain',
            '.json': 'application/json',
        }
        
        media_type = media_types.get(file_ext, 'application/octet-stream')
        
        return FileResponse(
            path=abs_path,
            media_type=media_type,
            filename=os.path.basename(abs_path)
        )
        
    except HTTPException:
        raise
    except Exception as e:
        logger.error(f"Error serving file {file_path} to user {user.username}: {e}", exc_info=True)
        raise HTTPException(status_code=500, detail="Internal server error")

@router.get("/plots/{plot_filename}")
async def serve_plot(
    plot_filename: str,
    user: AuthCredentials = Depends(get_current_user)
):
    """
    Convenience endpoint specifically for plot images.
    
    Serves plots from the plots subdirectory with additional security
    checks for image files.
    """
    # Validate filename format (should be UUID + extension)
    if not plot_filename or '..' in plot_filename:
        raise HTTPException(status_code=400, detail="Invalid plot filename")
    
    # Only allow image extensions for plots
    allowed_extensions = {'.png', '.jpg', '.jpeg', '.svg', '.pdf'}
    file_ext = os.path.splitext(plot_filename)[1].lower()
    
    if file_ext not in allowed_extensions:
        raise HTTPException(status_code=400, detail="Invalid plot file type")
    
    # Use the main file serving endpoint with plots/ prefix
    plot_path = f"plots/{plot_filename}"
    request = None  # This endpoint doesn't need the full request object
    
    return await serve_user_file(plot_path, user, request)