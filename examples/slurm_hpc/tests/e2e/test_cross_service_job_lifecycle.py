#SBATCH --job-name=adept_cross_service_e2e
#SBATCH --output=/data/adept_e2e_%j.out
#SBATCH --error=/data/adept_e2e_%j.err
#SBATCH --time=00:05:00
#SBATCH --nodes=1
#SBATCH --ntasks=1

# ============================================================================
# ADEPT Cross-Service E2E Test Script
# Generated by sandbox MCP server (simulated)
# Purpose: Capture compute-node metadata, sleep, exit cleanly
