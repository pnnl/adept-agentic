"""File routes — POST /v1/files/upload, GET /v1/files.

File upload and listing for ChatGPT Actions.
"""

from __future__ import annotations

import logging
from typing import Any, Optional

from fastapi import APIRouter, File, Form, Request, UploadFile
from pydantic import BaseModel, Field

router = APIRouter()
logger = logging.getLogger(__name__)


class FileMetadata(BaseModel):
    """File metadata returned by upload and list operations."""

    id: str = Field(..., description="ADEPT file ID")
    filename: str = Field(default="", description="Original filename")
    bytes: int = Field(default=0, description="File size in bytes")
    purpose: str = Field(default="assistants", description="Upload purpose")


class FileListResponse(BaseModel):
    """Response for GET /v1/files."""

    data: list[FileMetadata] = Field(default_factory=list)
    count: int = Field(default=0)


@router.post("/files/upload", response_model=FileMetadata)
async def upload_file(
    request: Request,
    file: UploadFile = File(..., description="File to upload"),
    purpose: str = Form(default="assistants", description="Upload purpose"),
    session_id: Optional[str] = Form(default=None, description="Session ID"),
) -> FileMetadata:
    """Upload a file to ADEPT for agent processing.

    Upload the file first, then reference the returned file_id in
    POST /v1/chat messages: "Analyze file_id: <id>".
    """
    facade = request.app.state.facade

    content = await file.read()

    import base64
    file_data = base64.b64encode(content).decode("ascii")

    result = await facade.files.upload(
        file_data=file_data,
        file_name=file.filename or "upload",
        purpose=purpose,
        session_id=session_id,
    )

    return FileMetadata(
        id=result.get("id", result.get("file_id", "")),
        filename=result.get("filename", file.filename or ""),
        bytes=result.get("bytes", len(content)),
        purpose=result.get("purpose", purpose),
    )


@router.get("/files", response_model=FileListResponse)
async def list_files(
    request: Request,
    session_id: Optional[str] = None,
) -> FileListResponse:
    """List files uploaded to or generated by ADEPT."""
    facade = request.app.state.facade
    files = await facade.files.list_files(session_id=session_id)

    items = [
        FileMetadata(
            id=f.get("id", f.get("file_id", "")),
            filename=f.get("filename", ""),
            bytes=f.get("bytes", 0),
            purpose=f.get("purpose", ""),
        )
        for f in files
    ]
    return FileListResponse(data=items, count=len(items))
