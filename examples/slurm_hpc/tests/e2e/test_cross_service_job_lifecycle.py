"""Cross-service E2E test: sandbox script generation -> shared volume -> Slurm submission.

This test validates the full workflow:
1. Generate a hello-world bash script (simulating sandbox MCP server output)
2. Write it to the shared slurm_workspace volume (accessible to compute nodes)
3. Submit the script to the local Docker Slurm cluster via slurmrestd
4. Monitor execution until COMPLETED or timeout
5. Verify output logs contain expected compute-node metadata

GUARDED: Requires the local Slurm Docker stack to be running (make start).
The test probes slurmctld health before executing.

The generated script:
- Logs hostname, kernel version, CPU info, memory stats, Slurm env vars
- Sleeps for 30 seconds (simulates computation)
- Exits cleanly with a success marker
"""

import json
import os
import socket
import sys
import time
import uuid

import pytest

# --- Path setup ---
SLURM_MCP_DIR = os.path.join(
    os.path.dirname(__file__), "..", "..", "slurm_mcp_server"
)
if SLURM_MCP_DIR not in sys.path:
    sys.path.insert(0, SLURM_MCP_DIR)

# --- Configuration ---
SLURM_API_URL = os.getenv("SLURM_API_URL", "http://slurmrestd:6820")
SLURM_WORKSPACE = os.getenv("SLURM_WORKSPACE", "/data")
CROSS_SERVICE_E2E_ENABLED = (
    os.getenv("CROSS_SERVICE_E2E_ENABLED", "false").lower() == "true"
)
DEFAULT_USER = os.getenv("SLURM_E2E_USER", "rigo160")
JOB_POLL_INTERVAL_SECONDS = 5
JOB_TIMEOUT_SECONDS = 180


# --- Guard decorators ---
def _can_reach_slurmctld() -> bool:
    """Check if the local Docker slurmctld is reachable."""
    try:
        sock = socket.create_connection(("slurmctld", 6817), timeout=3.0)
        sock.close()
        return True
    except (OSError, socket.timeout):
        return False


def _can_reach_slurmrestd() -> bool:
    """Check if slurmrestd API is reachable."""
    try:
        sock = socket.create_connection(("slurmrestd", 6820), timeout=3.0)
        sock.close()
        return True
    except (OSError, socket.timeout):
        return False


skip_cross_service = pytest.mark.skipif(
    not CROSS_SERVICE_E2E_ENABLED,
    reason="CROSS_SERVICE_E2E_ENABLED not set to 'true' (opt-in required)",
)


