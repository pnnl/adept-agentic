"""
File Management Tools for Sandbox MCP Server

This module provides self-contained file management tools for the sandbox MCP server,
specifically for files generated through code execution in the llm-sandbox environment.

Key Features:
- Session-isolated file listing for sandbox-generated files
- Basic content querying for generated files
- Separate from mcp_server's CSV RAG functionality
- Uses 'uploaded_files' session context key (vs 'uploaded_csv_files' in mcp_server)

Architectural Role:
- Tier 3 (Executor): Self-contained file management within secure sandbox environment
- No external dependencies on other MCP servers
- Session-scoped isolation with enhanced user context
"""
from fastmcp import FastMCP, Context
from ...core.session_api import get_session_client
from ...logger_config import get_logger
from typing import Dict, Any, Optional, List
import json
import os

logger = get_logger(__name__)

def register_file_management_tools(mcp: FastMCP):
    """Register file management tools with the sandbox MCP server."""
    
    @mcp.tool()
    async def get_session_workspace_path(
        ctx: Context,
        session_id: Optional[str] = None,
        mcp_session_id: Optional[str] = None,
        multi_agent_session_id: Optional[str] = None,
        gateway_session_id: Optional[str] = None,
        user_id: Optional[str] = None
    ) -> Dict[str, Any]:
        """
        Get the session-isolated workspace path for the current execution context.
        
        This tool returns the appropriate workspace path based on the multi-tier
        session hierarchy, ensuring proper isolation between users and sessions.
        
        Args:
            session_id: Primary session identifier
            mcp_session_id: MCP tool execution session
            multi_agent_session_id: Multi-agent coordination session
            gateway_session_id: Gateway communication session
            user_id: User identifier for session ownership
            
        Returns:
            Dictionary with workspace paths and session information
        """
        try:
            from ..session.session_manager import get_session_manager
            session_manager = get_session_manager()
            
            # Use session hierarchy to determine effective session ID
            effective_session_id = session_id or f"sandbox_{mcp_session_id or 'default'}_{user_id or 'unknown'}"
            
            # Get or create session
            session_info = session_manager.get_session(effective_session_id)
            if not session_info:
                session_info = session_manager.create_session(
                    session_id=effective_session_id,
                    user_id=user_id,
                    multi_agent_session_id=multi_agent_session_id,
                    gateway_session_id=gateway_session_id
                )
            
            await ctx.info(f"Session {effective_session_id} workspace configured")
            
            return {
                "session_id": effective_session_id,
                "workspace_path": session_info.workspace_path,
                "outputs_path": session_info.outputs_path,
                "user_id": session_info.user_id,
                "is_hybrid": session_manager.use_hybrid_approach,
                "base_shared_path": str(session_manager.base_shared_path),
                "tmpfs_available": session_manager.tmpfs_path.exists() if hasattr(session_manager, 'tmpfs_path') else False
            }
            
        except Exception as e:
            logger.error(f"Error getting session workspace: {e}", exc_info=True)
            await ctx.error(f"Failed to get session workspace: {e}")
            return {
                "error": str(e),
                "workspace_path": "/app/data/uploaded_files",  # Fallback
                "outputs_path": "/app/data/uploaded_files"
            }
    
    @mcp.tool()
    async def list_uploaded_files(
        ctx: Context,
        mcp_session_id: Optional[str] = None
    ) -> Dict[str, Any]:
        """
        Lists all files that have been generated by sandbox code execution
        in the current session.
        
        This tool is self-contained within sandbox_mcp_server and reads from
        the 'uploaded_files' session context key (separate from mcp_server's
        'uploaded_csv_files' used for CSV RAG).
        
        Args:
            mcp_session_id: MCP session ID for context isolation
            
        Returns:
            Dictionary containing list of generated files with metadata
        """
        try:
            if not mcp_session_id:
                logger.warning("list_uploaded_files called without mcp_session_id")
                return {
                    "uploaded_files": [], 
                    "message": "No session context available. Files are session-scoped."
                }
            
            await ctx.info(f"Sandbox Session {mcp_session_id}: Retrieving list of generated files.")
            
            # Get session context using the session API client
            session_client = get_session_client()
            current_session_data = await session_client.get_session_context(mcp_session_id)
            
            # Look for files in the 'uploaded_files' key (sandbox-generated files)
            uploaded_files_info = current_session_data.get("uploaded_files", {})
            
            if not uploaded_files_info:
                return {
                    "uploaded_files": [], 
                    "message": "No files have been generated by code execution in this session."
                }
                
            files_list = []
            for file_id, info in uploaded_files_info.items():
                files_list.append({
                    "file_id": file_id,
                    "filename": info.get("filename", info.get("original_filename", "N/A")),
                    "purpose": info.get("purpose", "assistant_generated"),
                    "created_at": info.get("created_at"),
                    "bytes": info.get("bytes", 0),
                    "generated_by": info.get("generated_by", "sandbox_mcp_server")
                })
            
            logger.info(f"Found {len(files_list)} generated files in session {mcp_session_id}")
            return {"uploaded_files": files_list}
            
        except Exception as e:
            logger.error(f"Error listing sandbox-generated files: {e}", exc_info=True)
            await ctx.error(f"Failed to list generated files: {e}")
            return {
                "uploaded_files": [], 
                "message": f"Error retrieving file list: {str(e)}"
            }
    
    @mcp.tool()
    async def query_generated_file_content(
        ctx: Context,
        file_id: str,
        query: str,
        mcp_session_id: Optional[str] = None
    ) -> Dict[str, Any]:
        """
        Performs basic content search on a sandbox-generated file.
        
        This provides simple text-based querying for files created through
        code execution. For more advanced RAG functionality on uploaded
        documents, use the mcp_server's CSV RAG tools instead.
        
        Args:
            file_id: ID of the file to query (from list_uploaded_files)
            query: Search query string
            mcp_session_id: MCP session ID for context isolation
            
        Returns:
            Dictionary with search results and file content excerpts
        """
        try:
            if not mcp_session_id:
                logger.warning("query_generated_file_content called without mcp_session_id")
                return {
                    "results": [],
                    "message": "No session context available. Files are session-scoped."
                }
            
            await ctx.info(f"Sandbox Session {mcp_session_id}: Querying file {file_id} with query: '{query}'")
            
            # Get session context to find file metadata
            session_client = get_session_client()
            current_session_data = await session_client.get_session_context(mcp_session_id)
            uploaded_files_info = current_session_data.get("uploaded_files", {})
            
            if file_id not in uploaded_files_info:
                return {
                    "results": [],
                    "message": f"File {file_id} not found in current session."
                }
            
            file_info = uploaded_files_info[file_id]
            filename = file_info.get("filename", "unknown")
            
            # For now, implement basic file content reading and text search
            # This is a simple implementation - could be enhanced with proper RAG later
            
            # Try to find the actual file path
            # Generated files are typically in session-specific directories
            possible_paths = [
                f"/app/data/uploaded_files/{file_id}",
                f"/app/data/uploaded_files/sessions/{mcp_session_id}/{filename}",
                f"/app/data/uploaded_files/{filename}",
            ]
            
            file_path = None
            for path in possible_paths:
                if os.path.exists(path):
                    file_path = path
                    break
            
            if not file_path:
                logger.warning(f"Physical file not found for {file_id} (filename: {filename})")
                return {
                    "results": [],
                    "message": f"File content not accessible for {filename}. File may have been cleaned up."
                }
            
            # Read and search file content
            try:
                with open(file_path, 'r', encoding='utf-8') as f:
                    content = f.read()
                
                # Simple text search - case insensitive
                lines = content.split('\n')
                matching_lines = []
                
                query_lower = query.lower()
                for i, line in enumerate(lines, 1):
                    if query_lower in line.lower():
                        matching_lines.append({
                            "line_number": i,
                            "content": line.strip(),
                            "context": lines[max(0, i-2):i+1]  # Include some context
                        })
                
                logger.info(f"Found {len(matching_lines)} matches for query '{query}' in {filename}")
                
                return {
                    "results": matching_lines,
                    "file_info": {
                        "file_id": file_id,
                        "filename": filename,
                        "total_lines": len(lines),
                        "file_size": len(content)
                    },
                    "query": query,
                    "message": f"Found {len(matching_lines)} matches in {filename}"
                }
                
            except UnicodeDecodeError:
                # File might be binary
                logger.info(f"File {filename} appears to be binary, cannot perform text search")
                return {
                    "results": [],
                    "message": f"File {filename} is binary and cannot be searched as text."
                }
                
        except Exception as e:
            logger.error(f"Error querying generated file content: {e}", exc_info=True)
            await ctx.error(f"Failed to query file content: {e}")
            return {
                "results": [],
                "message": f"Error querying file: {str(e)}"
            }

    logger.info("Sandbox file management tools registered.")